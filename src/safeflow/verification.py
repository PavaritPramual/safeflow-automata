"""Compile the finite IR to timed automata and retain real verifier evidence.

Clock constraints appear on edges, never in imperative boolean assignments.
The plant abstraction applies each declared action atomically at decision time;
arbitrary nonnegative environment delays are an over-approximation of the lab's
30-second steps. Physical thermal equations are outside this verification.
"""
import copy
import ast
import hashlib
import itertools
import json
import re
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path
from .core.definition import Definition, IR_VERSION, canonical, digest

CONVERTER_VERSION = 'safeflow-uppaal-1'


def file_hash(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_json(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n', encoding='utf-8')


def compile_model(definition):
    d = definition.data
    strings = set(d['sources'] + d['event_kinds'] + list(d['actions']) + ['none', 'allow', 'block', 'halt'])
    for spec in d['variables'].values():
        if spec['type'] == 'enum': strings.update(spec['values'])
    enums = {value: i for i, value in enumerate(sorted(strings))}
    names = {'source': 'source', 'kind': 'kind', 'action': 'action', 'outcome': 'outcome'}
    names.update({'params.' + k: 'p_' + k for k in d['parameters']})
    names.update({'clock.' + k: 'c_' + k for k in d['clocks']})
    names.update({'active.' + k: 'active_' + k for k in d['clocks']})
    for k in d['variables']:
        for prefix in ('facts', 'after'): names[prefix + '.' + k] = 'v_' + k
        names['before.' + k] = 'before_' + k

    def literal(value):
        if type(value) is bool: return str(value).lower()
        if type(value) is str: return str(enums[value])
        return str(value)

    declarations = ['// Generated by ' + CONVERTER_VERSION + '; definition ' + definition.sha256]
    for k, value in d['parameters'].items(): declarations.append(f'const int p_{k}={value};')
    for k, spec in d['variables'].items():
        if spec['type'] == 'bool': typ = 'bool'
        elif spec['type'] == 'int': typ = f"int[{spec['min']},{spec['max']}]"
        else: typ = 'int[0,' + str(max(enums[x] for x in spec['values'])) + ']'
        for prefix in ('v_', 'before_'): declarations.append(f'{typ} {prefix}{k}={literal(spec["initial"])};')
    for k in d['clocks']:
        declarations.extend([f'clock c_{k};', f'bool active_{k}=false;'])
    declarations.extend([f'int[0,{len(d["states"])-1}] control_state={d["states"].index(d["initial"])}, next_state={d["states"].index(d["initial"])};',
                         f'int[0,{len(enums)-1}] source={enums[d["sources"][0]]}, kind={enums["proposal"]}, action={enums["none"]}, outcome={enums["block"]};',
                         f'int[0,{len(d["transitions"])}] match_count=0;',
                         f'int[0,{len(d["transitions"])-1}] selected=0;',
                         'bool bad_complete=false;'])
    queries = [{'id': 'no_deadlock', 'formula': 'A[] not deadlock'},
               {'id': 'complete_decisions', 'formula': 'A[] !bad_complete'}]
    for i, prop in enumerate(d['properties']):
        flag = 'bad_' if prop['type'] == 'invariant' else 'seen_'
        declarations.append(f'bool {flag}{i}=false;')
        queries.append({'id': prop['id'], 'formula': f'A[] !bad_{i}' if prop['type'] == 'invariant' else f'E<> seen_{i}'})
    root = ET.Element('nta')
    ET.SubElement(root, 'declaration').text = '\n'.join(declarations)
    template = ET.SubElement(root, 'template'); ET.SubElement(template, 'name').text = 'Supervisor'
    locations = {}

    def loc(name, committed=True):
        ident = 'L' + str(len(locations))
        item = ET.SubElement(template, 'location', id=ident, x=str(len(locations)*160), y='0')
        ET.SubElement(item, 'name').text = name
        if committed: ET.SubElement(item, 'committed')
        locations[name] = ident
        return name

    def edge(start, end, guard=None, assignments=None, select=None):
        tr = ET.SubElement(template, 'transition')
        ET.SubElement(tr, 'source', ref=locations[start]); ET.SubElement(tr, 'target', ref=locations[end])
        for kind_, text in (('select', select), ('guard', guard), ('assignment', assignments)):
            if text: ET.SubElement(tr, 'label', kind=kind_).text = text

    loc('Idle', False); loc('Resolve'); loc('Apply'); loc('Waiting', False); loc('Observed'); loc('Stopped', False)
    ET.SubElement(template, 'init', ref=locations['Idle'])
    source_values, kind_values, action_values = d['sources'], d['event_kinds'], ['none'] + list(d['actions'])
    # Enumerate finite input symbols; no proposal can silently omit its action.
    for source, kind, action in itertools.product(source_values, kind_values, action_values):
        if (kind == 'proposal') != (action != 'none'): continue
        updates = [f'source={enums[source]}', f'kind={enums[kind]}', f'action={enums[action]}', 'match_count=0']
        updates += [f'before_{k}=v_{k}' for k in d['variables']]
        edge('Idle', 'Resolve', assignments=', '.join(updates))

    def fresh(): return loc('Condition' + str(len(locations)))

    def branch(start, yes, no, expression, node=None):
        """Lower Boolean structure to committed control flow, not clock ORs.

        UPPAAL guards accept conjunctions of clock constraints. Evaluating a
        Boolean expression as a decision graph avoids exponential DNF expansion.
        All intermediate locations are committed, so clocks cannot advance.
        """
        node = expression.tree if node is None else node
        if isinstance(node, ast.Constant) and type(node.value) is bool:
            edge(start, yes if node.value else no); return
        if isinstance(node, ast.UnaryOp):
            branch(start, no, yes, expression, node.operand); return
        if isinstance(node, ast.BoolOp):
            current = start
            for i, child in enumerate(node.values):
                last = i == len(node.values)-1
                target = (yes if isinstance(node.op, ast.And) else no) if last else fresh()
                branch(current, target if isinstance(node.op, ast.And) else yes,
                       no if isinstance(node.op, ast.And) else target, expression, child)
                current = target
            return
        if isinstance(node, ast.Compare) and len(node.ops) > 1:
            parts = [ast.Compare(left=a, ops=[op], comparators=[b]) for a,op,b in
                     zip([node.left]+node.comparators,node.ops,node.comparators)]
            branch(start, yes, no, expression, ast.BoolOp(op=ast.And(), values=parts)); return
        atom = copy.copy(expression); atom.tree = node
        if isinstance(node, ast.Compare):
            inverses = {ast.Eq:ast.NotEq, ast.NotEq:ast.Eq, ast.Lt:ast.GtE, ast.LtE:ast.Gt, ast.Gt:ast.LtE, ast.GtE:ast.Lt}
            clock_atom = any(isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id=='clock' for n in ast.walk(node))
            for truth, target, op in ((True,yes,type(node.ops[0])), (False,no,inverses[type(node.ops[0])])):
                ops = (ast.Lt,ast.Gt) if clock_atom and op is ast.NotEq else (op,)
                for actual_op in ops:
                    term=copy.copy(expression)
                    term.tree=ast.Compare(left=node.left,ops=[actual_op()],comparators=node.comparators)
                    edge(start,target,term.uppaal(names,enums))
        else:
            text=atom.uppaal(names,enums)
            edge(start,yes,text);edge(start,no,'!('+text+')')

    def property_chain(phase, start, end):
        props = [(i, p) for i, p in enumerate(d['properties']) if p['at'] == phase]
        current = start
        for j, (i, prop) in enumerate(props):
            target = end if j == len(props)-1 else loc(phase.title() + str(j))
            yes,no=fresh(),fresh()
            branch(current,yes,no,definition.assertions[prop['id']])
            edge(yes, target, assignments=f'seen_{i}=true' if prop['type'] == 'reachable' else None)
            edge(no, target, assignments=f'bad_{i}=true' if prop['type'] == 'invariant' else None)
            current = target
        if not props: edge(start, end)

    loc('Decided')
    current='Resolve'
    for i, e in enumerate(d['transitions']):
        next_check,check_guard,matched=fresh(),fresh(),fresh()
        kinds = '(' + ' || '.join('kind==' + str(enums[k]) for k in e['on']) + ')'
        prefix=f'(control_state=={d["states"].index(e["from"])} && {kinds})'
        edge(current,check_guard,prefix);edge(current,next_check,'!('+prefix+')')
        branch(check_guard,matched,next_check,definition.guards[e['id']])
        edge(matched,next_check,assignments=f'match_count=match_count+1, selected={i}')
        current=next_check
    for i,e in enumerate(d['transitions']):
        edge(current, 'Decided', f'match_count==1 && selected=={i}',
             f'outcome={enums[e["outcome"]]}, next_state={d["states"].index(e["to"])}')
    # Explicit fault branch makes missing/ambiguous guards visible to verification.
    edge(current, 'Decided', 'match_count!=1', f'bad_complete=true, outcome={enums["halt"]}, next_state=control_state')
    property_chain('decision', 'Decided', 'Apply')

    paths = [(f'outcome!={enums["allow"]}', {})]
    for action, spec in d['actions'].items():
        paths.append((f'outcome=={enums["allow"]} && action=={enums[action]}', spec['set']))
    for base_guard, effects in paths:
        after_names = {**names, **{'after.' + k: literal(effects[k]) if k in effects else 'v_' + k for k in d['variables']}}
        reset_expr = {k: expr.uppaal(after_names, enums) for k, expr in definition.clock_resets.items()}
        for choices in itertools.product((False, True), repeat=len(reset_expr)):
            guards = [base_guard]
            assignments = ['control_state=next_state'] + ['v_' + k + '=' + literal(value) for k, value in effects.items()]
            for (clock, expr), yes in zip(reset_expr.items(), choices):
                guards.append('(' + expr + ')' if yes else '!(' + expr + ')')
                if yes: assignments += ['c_' + clock + '=0', 'active_' + clock + '=true']
            edge('Apply', 'Waiting', ' && '.join(guards), ', '.join(assignments))
    # Runtime's allow-without-action guard is also represented explicitly.
    edge('Apply', 'Waiting', f'outcome=={enums["allow"]} && action=={enums["none"]}', f'bad_complete=true, outcome={enums["halt"]}')
    edge('Waiting', 'Observed')
    loc('Finished'); property_chain('observation', 'Observed', 'Finished')
    edge('Finished', 'Idle', f'outcome!={enums["halt"]}')
    edge('Finished', 'Stopped', f'outcome=={enums["halt"]}')
    edge('Stopped', 'Stopped')
    # Flat XML requires all locations before init and all transitions after it.
    # Property-chain construction above creates locations incrementally.
    children = list(template)
    template[:] = ([x for x in children if x.tag == 'name'] +
                   [x for x in children if x.tag == 'location'] +
                   [x for x in children if x.tag == 'init'] +
                   [x for x in children if x.tag == 'transition'])
    ET.SubElement(root, 'system').text = 'S=Supervisor(); system S;'
    xml_queries = ET.SubElement(root, 'queries')
    for query in queries:
        q = ET.SubElement(xml_queries, 'query'); ET.SubElement(q, 'formula').text = query['formula']
        ET.SubElement(q, 'comment').text = query['id']
    ET.indent(root)
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
           '<!DOCTYPE nta PUBLIC "-//Uppaal Team//DTD Flat System 1.1//EN" "http://www.it.uu.se/research/group/darts/uppaal/flat-1_2.dtd">\n'
           + ET.tostring(root, encoding='unicode') + '\n')
    return xml, queries


def artifact_identity(definition):
    xml, queries = compile_model(definition)
    package = Path(__file__).parent
    implementation = {name: hashlib.sha256((package / name).read_text(encoding='utf-8').encode()).hexdigest() for name in
                      ('core/definition.py', 'core/expressions.py', 'core/runtime.py', 'verification.py', 'service.py')}
    return {'definition_sha256': definition.sha256, 'ir_sha256': definition.ir_sha256,
            'ir_version': IR_VERSION, 'converter_version': CONVERTER_VERSION,
            'implementation_sha256': digest(implementation),
            'model_sha256': hashlib.sha256(xml.encode()).hexdigest(), 'properties_sha256': digest(queries)}


def build_bundle(definition, directory):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    if any(directory.iterdir()): raise ValueError('verification_output_must_be_empty')
    xml, queries = compile_model(definition)
    (directory / 'model.xml').write_text(xml, encoding='utf-8', newline='\n')
    write_json(directory / 'definition.json', definition.data)
    write_json(directory / 'ir.json', {'ir_version': IR_VERSION, 'definition': definition.data})
    write_json(directory / 'properties.json', queries)
    write_json(directory / 'manifest.json', artifact_identity(definition))
    for i, query in enumerate(queries): (directory / f'query-{i:03}.q').write_text(query['formula'] + '\n', encoding='utf-8')
    return directory


class UppaalVerifier:
    def __init__(self, executable, timeout_s=30):
        self.executable = Path(executable).resolve()
        if not self.executable.is_file(): raise ValueError('verifier_executable_not_found')
        if not 0 < timeout_s <= 600: raise ValueError('invalid_verifier_timeout')
        self.timeout_s = timeout_s

    def verify(self, directory):
        directory = Path(directory).resolve()
        definition = Definition(json.loads((directory / 'definition.json').read_text(encoding='utf-8')))
        validate_bundle_files(definition, directory)
        queries = json.loads((directory / 'properties.json').read_text(encoding='utf-8'))
        results = []
        for i, query in enumerate(queries):
            started = time.perf_counter()
            try:
                p = subprocess.run([str(self.executable), str(directory / 'model.xml'), str(directory / f'query-{i:03}.q')],
                                   capture_output=True, text=True, timeout=self.timeout_s, encoding='utf-8', errors='replace')
                output = p.stdout + p.stderr
                verdicts = re.findall(r'Formula is (NOT satisfied|satisfied)\.', output)
                if 'License does not cover verifier.' in output:
                    status = 'unavailable'
                elif p.returncode == 0 and verdicts == ['satisfied']:
                    status = 'passed'
                elif p.returncode == 0 and verdicts == ['NOT satisfied']:
                    status = 'failed'
                else:
                    status = 'error'  # Syntax errors must not become skipped proof tests.
                code = p.returncode
            except subprocess.TimeoutExpired:
                output, status, code = 'verifier_timeout', 'timeout', None
            except OSError as exc:
                output, status, code = type(exc).__name__ + ': ' + str(exc), 'unavailable', None
            filename = f'verifier-{i:03}.txt'
            (directory / filename).write_text(output, encoding='utf-8', newline='\n')
            results.append({'id': query['id'], 'status': status, 'exit_code': code, 'output_file': filename,
                            'output_sha256': file_hash(directory / filename), 'elapsed_s': time.perf_counter()-started})
            if status in ('unavailable', 'timeout', 'error'):
                results += [{'id': q['id'], 'status': 'not_run'} for q in queries[i+1:]]
                break
        report = {**artifact_identity(definition), 'origin': 'uppaal_subprocess',
                  'verifier_executable': str(self.executable), 'verifier_sha256': file_hash(self.executable),
                  'results': results, 'status': 'passed' if all(x['status'] == 'passed' for x in results) else 'not_ready'}
        try:
            p = subprocess.run([str(self.executable), '--version'], capture_output=True, text=True, timeout=10, encoding='utf-8', errors='replace')
            report['verifier_version'] = (p.stdout + p.stderr).strip()
        except (OSError, subprocess.TimeoutExpired): report['verifier_version'] = 'unavailable'
        write_json(directory / 'verification.json', report)
        return report


def validate_bundle_files(definition, directory):
    directory = Path(directory)
    manifest = json.loads((directory / 'manifest.json').read_text(encoding='utf-8'))
    if manifest != artifact_identity(definition): raise ValueError('verification_manifest_mismatch')
    if file_hash(directory / 'model.xml') != manifest['model_sha256']: raise ValueError('verification_model_mismatch')
    props = json.loads((directory / 'properties.json').read_text(encoding='utf-8'))
    if digest(props) != manifest['properties_sha256']: raise ValueError('verification_properties_mismatch')
    ir = json.loads((directory / 'ir.json').read_text(encoding='utf-8'))
    if digest(ir) != definition.ir_sha256: raise ValueError('verification_ir_mismatch')
    for i, q in enumerate(props):
        if (directory / f'query-{i:03}.q').read_text(encoding='utf-8') != q['formula'] + '\n':
            raise ValueError('verification_query_mismatch')


class VerificationGate:
    """Receipts are trusted local administrator files, never uploaded over HTTP.

Hashes detect stale/modified artifacts, not a malicious local administrator.
Only the real verifier implementation issues production receipts.
"""
    def __init__(self, directory): self.directory = Path(directory)

    def require(self, definition):
        validate_bundle_files(definition, self.directory)
        report = json.loads((self.directory / 'verification.json').read_text(encoding='utf-8'))
        identity = artifact_identity(definition)
        if any(report.get(k) != value for k, value in identity.items()): raise ValueError('verification_identity_mismatch')
        if report.get('origin') != 'uppaal_subprocess' or report.get('status') != 'passed': raise ValueError('policy_not_verified')
        results = report.get('results', [])
        if [x.get('id') for x in results] != definition.property_ids or any(x.get('status') != 'passed' or x.get('exit_code') != 0 for x in results):
            raise ValueError('verification_incomplete')
        if file_hash(report['verifier_executable']) != report['verifier_sha256']: raise ValueError('verifier_binary_changed')
        for i, result in enumerate(results):
            if result.get('output_file') != f'verifier-{i:03}.txt': raise ValueError('invalid_verification_output_path')
            path = self.directory / result['output_file']
            if file_hash(path) != result.get('output_sha256') or re.findall(r'Formula is (NOT satisfied|satisfied)\.', path.read_text(encoding='utf-8')) != ['satisfied']:
                raise ValueError('verification_output_mismatch')
        return copy.deepcopy(report)
