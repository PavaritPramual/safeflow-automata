"""Small structural interfaces: implementations need no shared base class."""
from typing import Protocol, Any
from .core.definition import Definition


class EventSink(Protocol):
    def write(self, event: dict) -> None: ...


class VerificationPort(Protocol):
    def require(self, definition: Definition) -> dict: ...


class Proposer(Protocol):
    def metadata(self) -> dict: ...
    def propose(self, observation: dict, seed: int = 0) -> dict: ...
    def normalize(self, raw: dict) -> dict: ...


class Environment(Protocol):
    def sample(self) -> dict: ...
    def execute(self, action: str | None) -> dict: ...
    def set_goals(self, values: dict) -> None: ...
    def reset(self, scenario: dict | None = None) -> dict: ...
